#!/bin/bash
# Start the nfsc test servers as rootful podman containers on a private network.
#   up.sh [knfsd|ganesha|all]     default: all
# Idempotent: running containers are kept, missing images are built, and the
# env file is rewritten from the servers that are actually up.
# Env: NFSC_TESTENV_FILE (env file, default testenv/testenv.env, gitignored),
#      NFSC_TESTENV_SUBNET (default 10.89.0.0/24), NFSC_TESTENV_REBUILD=1.
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
WHAT=${1:-all}
NET=nfsc-testenv
SUBNET=${NFSC_TESTENV_SUBNET:-10.89.0.0/24}
ENV_FILE=${NFSC_TESTENV_FILE:-$HERE/testenv.env}
SUDO_PODMAN=(sudo podman)
log() { echo "[up] $*" >&2; }

case "$WHAT" in knfsd|ganesha|all) ;; *) echo "usage: up.sh [knfsd|ganesha|all]" >&2; exit 2;; esac

# Kernel nfsd needs the module; the nfsd filesystem is mounted by the container.
grep -q '^nfsd ' /proc/modules || sudo modprobe nfsd

"${SUDO_PODMAN[@]}" network exists "$NET" 2>/dev/null ||
    "${SUDO_PODMAN[@]}" network create --subnet "$SUBNET" "$NET" >/dev/null

ensure_image() { # image containerfile
    if [ -n "${NFSC_TESTENV_REBUILD:-}" ] || ! "${SUDO_PODMAN[@]}" image exists "$1"; then
        log "building $1"
        "${SUDO_PODMAN[@]}" build -q -t "$1" -f "$HERE/$2" "$HERE" >/dev/null
    fi
}

running() { [ "$("${SUDO_PODMAN[@]}" inspect -f '{{.State.Running}}' "$1" 2>/dev/null)" = true ]; }

ensure_container() { # name image [extra run args...]
    local name=$1 image=$2; shift 2
    if [ -n "${NFSC_TESTENV_REBUILD:-}" ] && "${SUDO_PODMAN[@]}" container exists "$name"; then
        "${SUDO_PODMAN[@]}" rm -f "$name" >/dev/null
    fi
    if running "$name"; then
        log "$name already running"
        return 0
    fi
    "${SUDO_PODMAN[@]}" rm -f "$name" >/dev/null 2>&1 || true
    log "starting $name"
    "${SUDO_PODMAN[@]}" run -d --name "$name" --privileged --network "$NET" "$@" "$image" >/dev/null
}

container_ip() {
    "${SUDO_PODMAN[@]}" inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$1"
}

wait_ready() { # ip -> 0 when RPC portmap, MOUNT and NFS port all answer
    local ip=$1 i
    for i in $(seq 1 60); do
        if timeout 3 rpcinfo -p "$ip" >/dev/null 2>&1 &&
           timeout 5 showmount -e "$ip" >/dev/null 2>&1 &&
           timeout 2 bash -c "</dev/tcp/$ip/2049" 2>/dev/null; then
            return 0
        fi
        sleep 1
    done
    return 1
}

if [ "$WHAT" = all ] || [ "$WHAT" = knfsd ]; then
    ensure_image localhost/nfsc-testenv-knfsd knfsd/Containerfile
    ensure_container nfsc-knfsd localhost/nfsc-testenv-knfsd
fi
if [ "$WHAT" = all ] || [ "$WHAT" = ganesha ]; then
    ensure_image localhost/nfsc-testenv-ganesha ganesha/Containerfile
    ensure_container nfsc-ganesha localhost/nfsc-testenv-ganesha \
        -v nfsc-ganesha-rw:/export/rw -v nfsc-ganesha-ro:/export/ro
fi

# Rebuild the env file from the servers that answer. Written atomically.
tmp=$(mktemp "$ENV_FILE.XXXXXX")
{
    echo "# generated by testenv/up.sh at $(date -Is); do not edit"
    for pair in knfsd:KNFSD ganesha:GANESHA; do
        srv=${pair%%:*}; key=${pair##*:}
        name=nfsc-$srv
        running "$name" || continue
        ip=$(container_ip "$name")
        if [ -z "$ip" ] || ! wait_ready "$ip"; then
            log "$name at ${ip:-no-ip} did not become ready; leaving it out of env file"
            continue
        fi
        echo "NFSC_TEST_RW_$key=$ip:/export/rw"
        echo "NFSC_TEST_RO_$key=$ip:/export/ro"
        echo "NFSC_TEST_ADDR_$key=$ip"
    done
    echo "NFSC_TEST_FIXTURES_SHA256=$HERE/fixtures.sha256"
    echo "NFSC_TEST_FIXTURES_ROOT=$HERE"
} > "$tmp"
chmod 0644 "$tmp"
mv -f "$tmp" "$ENV_FILE"
cat "$ENV_FILE"
log "env file: $ENV_FILE"
